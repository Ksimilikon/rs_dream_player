//! Пустая реализация медиа-транспорта. Используется на всех платформах без
//! активной интеграции: macOS/iOS/Android/прочие, а также **Windows при простой
//! сборке без `with_tui`** (souvlaki-бэкенд требует окна консоли и собирается
//! только в TUI-сборке — см. `lib.rs`). Проект — это ядро плеера; нативная
//! интеграция придёт вместе с фронтендом. Пока просто держим канал обновлений
//! живым и не шлём наружу никаких команд.
//!
//! Включение модуля целиком управляется `cfg` в `lib.rs`, поэтому здесь
//! собственного `#![cfg(...)]` нет (иначе он ошибочно вырезал бы тело под
//! Windows).

use std::error::Error;

use super::*;

impl DBus {
    /// заглушка: тихо поглощает обновления метаданных, пока ядро работает,
    /// команд управления не порождает. Блокирует поток (как и остальные версии).
    pub fn run(self) -> Result<(), Box<dyn Error>> {
        let DBus { tx: _, rx } = self;
        // держим приёмник живым: обновления метаданных просто отбрасываем.
        while rx.recv().is_ok() {}
        Ok(())
    }
}
